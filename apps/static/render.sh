#!/usr/bin/env bash
# Called by `kioskctl apply` for every app of type static: nginx site, content dir, update unit.
#   render.sh <name>     (env from /opt/kiosk/state/apps/<name>.env)
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../lib/common.sh"
LOG_TAG="app:static"
name="${1:?name}"
set -a; source "${KIOSK_STATE}/apps/${name}.env"; set +a

port="${APP_PORT:-8080}"
appdir="${KIOSK_DIR}/apps/${name}"
install -d -o "$KIOSK_USER" -g "$KIOSK_USER" "$appdir"

need_sync=0
if [ -n "${APP_REPO:-}" ]; then
    root="${appdir}/repo${APP_SUBDIR:+/${APP_SUBDIR}}"
    [ -d "${appdir}/repo/.git" ] || need_sync=1
else
    root="${APP_PATH:-${appdir}/site}"
    if [ ! -e "$root" ]; then
        install -d -o "$KIOSK_USER" -g "$KIOSK_USER" "$root"
        printf '<!doctype html><meta charset="utf-8"><title>%s</title><body style="margin:0;background:#111;color:#eee;font:5vw sans-serif;display:grid;place-items:center;height:100vh">kiosk app "%s": put your site in %s</body>\n' "$name" "$name" "$root" > "$root/index.html"
        chown "$KIOSK_USER:$KIOSK_USER" "$root/index.html"
        log "placeholder site written to $root"
    fi
fi

data_block=""
if [ -n "${APP_DATA_REPO:-}" ]; then
    [ -d "${appdir}/data/.git" ] || need_sync=1
    data_root="${appdir}/data${APP_DATA_SUBDIR:+/${APP_DATA_SUBDIR}}"
    data_url="${APP_DATA_URL:-/data}"; data_url="/${data_url#/}"; data_url="${data_url%/}"
    data_block="
    # data repo: always revalidated (ETag), so a pulled change is visible after a reload
    location ${data_url}/ {
        alias ${data_root}/;
        add_header Cache-Control \"no-cache\";
    }"
fi
if [ "$need_sync" = 1 ]; then
    "${KIOSK_SYS}/apps/static/update.sh" "$name" || warn "clone failed for '${name}'; retried at boot / by the timer or with: kioskctl app update ${name}"
fi

write_file "/etc/nginx/sites-available/kiosk-${name}.conf" <<NGX || true
# generated by kioskctl apply — app '${name}'
server {
    listen 127.0.0.1:${port};
    server_name _;
    root ${root};
    index index.html;
    access_log off;
    location / { try_files \$uri \$uri/ /index.html; }${data_block}
}
NGX
ln -sfn "/etc/nginx/sites-available/kiosk-${name}.conf" "/etc/nginx/sites-enabled/kiosk-${name}.conf"
nginx -t >/dev/null 2>&1 && systemctl reload nginx || warn "nginx config test failed for ${name}"

has_repo=0; [ -n "${APP_REPO:-}${APP_DATA_REPO:-}" ] && has_repo=1
if [ "${APP_UPDATE_ON_BOOT:-false}" = "true" ] && [ "$has_repo" = 1 ]; then
    systemctl enable "kiosk-content-update@${name}.service" >/dev/null 2>&1
else
    systemctl disable "kiosk-content-update@${name}.service" >/dev/null 2>&1 || true
fi
interval="${APP_UPDATE_INTERVAL:-0}"
if [ "$has_repo" = 1 ] && [ "$interval" != "0" ] && [ -n "$interval" ]; then
    [[ "$interval" =~ ^[0-9]+(s|m|h|min)?$ ]] || { warn "update_interval '$interval' invalid, using 15m"; interval=15m; }
    mkdir -p "/etc/systemd/system/kiosk-content-update@${name}.timer.d"
    printf '[Timer]\nOnUnitActiveSec=%s\n' "$interval" | write_file "/etc/systemd/system/kiosk-content-update@${name}.timer.d/interval.conf" || true
    systemctl daemon-reload
    systemctl enable --now "kiosk-content-update@${name}.timer" >/dev/null 2>&1
    log "$name: content update every $interval"
else
    systemctl disable --now "kiosk-content-update@${name}.timer" >/dev/null 2>&1 || true
    rm -rf "/etc/systemd/system/kiosk-content-update@${name}.timer.d"
    systemctl daemon-reload
fi
