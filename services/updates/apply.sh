#!/usr/bin/env bash
# services.updates: unattended Ubuntu updates (security only by default) with an optional reboot time.
#   enabled: false | true
#   security_only: true        false = all updates from the configured apt sources
#   reboot: "03:30" | ""       empty = never reboot automatically (status shows REBOOT REQUIRED instead)
# Refused while the root is overlaid (locked / data mode): the packages would vanish at reboot.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../lib/common.sh"
LOG_TAG="updates"
conf=/etc/apt/apt.conf.d/52-kiosk-unattended.conf
if [ "$(cfg '.services.updates.enabled' false)" != "true" ]; then
    [ -f "$conf" ] && { rm -f "$conf"; systemctl disable --now apt-daily-upgrade.timer >/dev/null 2>&1 || true; log "unattended updates off"; }
    exit 0
fi
if overlayroot_active; then
    warn "unattended updates need a writable root (mode $(persistence_mode)); not enabled"
    exit 0
fi
apt_install unattended-upgrades
sec_only="$(cfg '.services.updates.security_only' true)"
reboot="$(cfg '.services.updates.reboot')"
[ -z "$reboot" ] || [[ "$reboot" =~ ^([01][0-9]|2[0-3]):[0-5][0-9]$ ]] || { warn "updates.reboot '$reboot' is not HH:MM, no automatic reboot"; reboot=""; }
origins='"${distro_id}:${distro_codename}-security";'
[ "$sec_only" = true ] || origins="$origins
    \"\${distro_id}:\${distro_codename}\";
    \"\${distro_id}:\${distro_codename}-updates\";"
write_file "$conf" <<CONF || true
// generated by kioskctl apply (services.updates)
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT::Periodic::AutocleanInterval "7";
Unattended-Upgrade::Allowed-Origins {
    ${origins}
};
Unattended-Upgrade::Package-Blacklist { "google-chrome-stable"; };
Unattended-Upgrade::Remove-Unused-Dependencies "true";
Unattended-Upgrade::Automatic-Reboot "$([ -n "$reboot" ] && echo true || echo false)";
Unattended-Upgrade::Automatic-Reboot-Time "${reboot:-02:00}";
Unattended-Upgrade::SyslogEnable "true";
CONF
systemctl enable --now apt-daily.timer apt-daily-upgrade.timer >/dev/null 2>&1 || true
log "unattended updates on: $([ "$sec_only" = true ] && echo security only || echo all updates), reboot ${reboot:-never}. Chrome is excluded (pinned by the kiosk)."
